#!/usr/bin/env python3
"""Check local Markdown links and explicit anchors in docs. Run from repo root.

This is a basic first pass, not a full MkDocs build. It skips remote links, image
links and source-code line fragment formats; confirm published navigation separately.
"""
from pathlib import Path
from urllib.parse import unquote
import re, sys
root=Path(__file__).resolve().parent
# Reader-facing docs have no example-only links; agent and template files do.
sources=list((root/'docs').rglob('*.md'))+[root/'READ_ME_FIRST.md']
errors=[]
for src in sources:
    if not src.exists(): continue
    txt=src.read_text(encoding='utf-8')
    for target in re.findall(r'(?<!!)\[[^\]]+\]\(([^)]+)\)',txt):
        target=target.strip().split(' ',1)[0]
        if target.startswith(('https:','http:','mailto:','#')): continue
        filepath,sep,frag=target.partition('#')
        dest=(src.parent/unquote(filepath)).resolve()
        if filepath and not dest.exists(): errors.append(f'{src.relative_to(root)}: missing file {filepath}')
        # heading slugs are generated by renderers; explicit anchors are checked here.
        if frag and dest.is_file() and dest.suffix=='.md':
            body=dest.read_text(encoding='utf-8')
            if not re.search(fr'<a\s+id=["\']{re.escape(frag)}["\']',body) and not re.search(r'^#{1,6} ',body,re.M):
                errors.append(f'{src.relative_to(root)}: possibly missing anchor {target}')
if errors:
    print('\n'.join(errors))
    sys.exit(1)
print(f'OK: Checked file targets from {len(sources)} Markdown pages. Verify symbol anchors during real documentation generation.')
